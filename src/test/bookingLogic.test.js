
import { describe, expect, it } from 'vitest'
import { datesOverlap } from '../utils/bookingLogic.js'

describe('Логіка бронювання готелю', () => {
  it('визначає перетин дат бронювань', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-15',
        '2026-11-12',
        '2026-11-17'
      )
    ).toBe(true)
  })

  it('не вважає сусідні дати перетином', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-15',
        '2026-11-15',
        '2026-11-20'
      )
    ).toBe(false)
  })

  it('визначає бронювання без перетину дат', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-12',
        '2026-11-15',
        '2026-11-18'
      )
    ).toBe(false)
  })

  it('визначає повне вкладення одного періоду в інший', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-20',
        '2026-11-12',
        '2026-11-15'
      )
    ).toBe(true)
  })

  it('не вважає перетином виїзд у день наступного заїзду', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-12',
        '2026-11-12',
        '2026-11-14'
      )
    ).toBe(false)
  })

  it('визначає перетин тривалістю один день', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-12',
        '2026-11-11',
        '2026-11-15'
      )
    ).toBe(true)
  })

  it('визначає однакові періоди як перетин', () => {
    expect(
      datesOverlap(
        '2026-11-10',
        '2026-11-15',
        '2026-11-10',
        '2026-11-15'
      )
    ).toBe(true)
  })
})
